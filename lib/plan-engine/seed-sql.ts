// Turns the mission library into the SQL seed for `mission_library`.
// `npm run gen:missions` writes it to a new migration; a unit test checks the
// newest seed migration still matches lib/plan-engine/missions.ts.
import type { Mission } from "./missions";

function text(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function textArray(values: string[]): string {
  return values.length === 0 ? "'{}'::text[]" : `array[${values.map(text).join(", ")}]::text[]`;
}

export function missionSeedSql(missions: Mission[]): string {
  const rows = missions.map(
    (m) =>
      `  (${[
        text(m.id),
        text(m.pillar),
        text(m.title),
        text(m.howTo),
        m.minutes,
        text(m.cost),
        text(m.needs),
        m.difficulty,
        textArray(m.archetypes),
        m.act,
        textArray(m.tags),
        m.pack === null ? "null" : text(m.pack),
      ].join(", ")})`,
  );

  return [
    "-- Generated by `npm run gen:missions` from lib/plan-engine/missions.ts. Don't edit by hand.",
    "insert into public.mission_library",
    "  (id, pillar, title, how_to, minutes, cost, needs, difficulty, archetypes, act, tags, pack)",
    "values",
    rows.join(",\n"),
    "on conflict (id) do update set",
    "  pillar = excluded.pillar, title = excluded.title, how_to = excluded.how_to,",
    "  minutes = excluded.minutes, cost = excluded.cost, needs = excluded.needs,",
    "  difficulty = excluded.difficulty, archetypes = excluded.archetypes, act = excluded.act,",
    "  tags = excluded.tags, pack = excluded.pack, active = true;",
    "",
    "-- Missions removed from the library stay for history but are no longer picked.",
    `update public.mission_library set active = false where id not in (${missions.map((m) => text(m.id)).join(", ")});`,
    "",
  ].join("\n");
}
